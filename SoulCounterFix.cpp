// The soul counter rolls up at the 30 FPS speed at any frame rate.
//
// THE BUG
//
// When souls are gained, the HUD soul counter (FrpgMenuDlgFEGetSoul, update fn 0x00FADA70) counts the shown number
// up to the new total. Every update it adds a step worked out from what is still left (0x00FADBE1..0x00FADCAE):
// +1 for anything left, +1 more above 10, +10 above 100, +100 above 1000, ... up to +10,000,000 above 100,000,000
// (the same downwards when souls are lost). The step is added once per FRAME (0x00FADCB1) and the frame time
// (the update's argument) is not used for it; it is only used for the pause after the count ends.
// So at 144 FPS the count runs 4.8 times faster than the game intended: 1,000 souls take 4.3 s at 30 FPS but 0.9 s
// at 144 FPS.
//
// THE FIX
//
// The game's own step is scaled by the frame time: (frame time x 30) steps are added, so one 30 FPS frame of time
// adds exactly one step, as at 30 FPS. The part of a soul that does not fit is carried to the next frame, so the
// count moves smoothly and takes the same time as at 30 FPS (worked out: within a few % for any gain, also with
// uneven frame times; measured in game with a trace build: 20,000 souls in 7.11 s at 144 FPS and 6.97 s at 30 FPS,
// the game at 30 FPS takes 7.00 s). The game still stops the count at the right total itself (0x00FADCB7..0x00FADCCB), so it
// can never overshoot. One update counts at most 4 steps (a long hitch must not jump the count).
// At 30 FPS this changes nothing, and it is not installed there.
//
// HOW IT IS PATCHED (checked byte for byte at start-up; jumps to the site only land on its first byte)
//
//   0x00FADCB1  add dword ptr [esi+108h], ecx   (6 bytes)   -> jmp soulRollStub, nop
//
// esi is the soul counter dialog, ecx the game's step, edx the target, [ebp+8] the frame time (the function keeps an
// ebp frame). The stub asks soulRollAmount how much to add, adds it and jumps back to 0x00FADCB7.

